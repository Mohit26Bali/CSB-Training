// Keeps the frontend in sync with the backend (D24).
//
//   npm run gen:api     fetch the OpenAPI file of each running service, save it in openapi/, generate the types
//   npm run gen:types   only generate the types from the saved files (the services need not run)
//   npm run check:api   fetch the files again and fail if they differ from the saved ones (exit code 1)
//
// The five services must be running for gen:api and check:api (see the README). The paths below are not routed
// by the gateway, so each service is asked directly on its own port.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specDir = join(root, 'openapi');
const typesDir = join(root, 'src', 'api', 'generated');

const services = {
  assignment: 8082,
  incident: 8086,
  'major-incident': 8083,
  rca: 8084,
  dashboard: 8085,
};

// SERVICE_PORT_OFFSET=10000 reads 18082 instead of 8082, and so on: for a second copy of the backend on other ports.
const offset = Number(process.env.SERVICE_PORT_OFFSET || 0);

const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--offline') ? 'offline' : 'write';

async function fetchSpec(name, port) {
  const url = `http://localhost:${port + offset}/v3/api-docs`;
  let response;
  try {
    response = await fetch(url);
  } catch {
    throw new Error(`Cannot reach ${name}-service at ${url}. Start the services first (see README).`);
  }
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  const spec = await response.json();
  // The server address differs per service and the frontend uses the gateway, so it is not part of the contract.
  delete spec.servers;
  return JSON.stringify(spec, null, 2) + '\n';
}

async function typesFor(specText) {
  const ast = await openapiTS(JSON.parse(specText));
  return (
    '// AUTO-GENERATED by `npm run gen:api` from openapi/. Do not edit by hand.\n' +
    '// A change in a backend endpoint or DTO shows up here and breaks the build where the old shape is used.\n\n' +
    astToString(ast)
  );
}

mkdirSync(specDir, { recursive: true });
mkdirSync(typesDir, { recursive: true });

let differences = 0;
for (const [name, port] of Object.entries(services)) {
  const specFile = join(specDir, `${name}.json`);
  const typesFile = join(typesDir, `${name}.ts`);

  let specText;
  if (mode === 'offline') {
    if (!existsSync(specFile)) throw new Error(`${specFile} is missing. Run npm run gen:api with the services running.`);
    specText = readFileSync(specFile, 'utf8');
  } else {
    specText = await fetchSpec(name, port);
  }
  const typesText = await typesFor(specText);

  if (mode === 'check') {
    const savedSpec = existsSync(specFile) ? readFileSync(specFile, 'utf8') : '';
    const savedTypes = existsSync(typesFile) ? readFileSync(typesFile, 'utf8') : '';
    if (savedSpec !== specText || savedTypes !== typesText) {
      differences++;
      console.error(`OUT OF DATE: ${name} (the backend contract changed). Run npm run gen:api and commit the result.`);
    } else {
      console.log(`ok: ${name}`);
    }
  } else {
    if (mode === 'write') writeFileSync(specFile, specText);
    writeFileSync(typesFile, typesText);
    console.log(`${mode === 'write' ? 'fetched and generated' : 'generated'}: ${name}`);
  }
}

if (mode === 'check' && differences > 0) process.exit(1);
