-- V1: the initial schema for H2, the in-memory database used by the automated tests (see src/test/resources).
-- It mirrors db/migration/mysql/V1__initial_schema.sql table for table; only the column syntax differs
-- (BOOLEAN instead of BIT(1), TIMESTAMP(6) instead of DATETIME(6), identity columns). Flyway picks the folder that
-- matches the connected database (spring.flyway.locations=classpath:db/migration/{vendor}).
-- Because the tests run Hibernate with ddl-auto=validate against this schema, a test run fails if an entity and a
-- migration ever drift apart. Keep both folders in step: every new V<n> script must exist in both.

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled   BOOLEAN      NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    password  VARCHAR(100) NOT NULL,
    role      ENUM ('ADMIN', 'CUSTOMER') NOT NULL,
    username  VARCHAR(50)  NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE customers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address    VARCHAR(255)  NOT NULL,
    created_at TIMESTAMP(6)  NOT NULL,
    email      VARCHAR(100)  NOT NULL,
    mobile     VARCHAR(15)   NOT NULL,
    user_id    BIGINT        NOT NULL,
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT uk_customers_user UNIQUE (user_id),
    CONSTRAINT fk_customers_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(20)    NOT NULL,
    account_type   ENUM ('CURRENT', 'SAVINGS') NOT NULL,
    balance        DECIMAL(19, 2) NOT NULL,
    created_at     TIMESTAMP(6)   NOT NULL,
    status         ENUM ('ACTIVE', 'BLOCKED', 'INACTIVE') NOT NULL,
    version        BIGINT         NOT NULL,
    customer_id    BIGINT         NOT NULL,
    CONSTRAINT uk_accounts_number UNIQUE (account_number),
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

CREATE TABLE transactions (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount                      DECIMAL(19, 2) NOT NULL,
    balance_after               DECIMAL(19, 2) NOT NULL,
    counterparty_account_number VARCHAR(20),
    created_at                  TIMESTAMP(6)   NOT NULL,
    description                 VARCHAR(255),
    direction                   ENUM ('CREDIT', 'DEBIT') NOT NULL,
    status                      ENUM ('FAILED', 'SUCCESS') NOT NULL,
    transaction_ref             VARCHAR(36)    NOT NULL,
    type                        ENUM ('DEPOSIT', 'TRANSFER', 'WITHDRAWAL') NOT NULL,
    account_id                  BIGINT         NOT NULL,
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id)
);
CREATE INDEX idx_txn_account_created ON transactions (account_id, created_at);

CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6)  NOT NULL,
    idempotency_key VARCHAR(64)   NOT NULL,
    request_hash    VARCHAR(64)   NOT NULL,
    response_body   VARCHAR(4000),
    username        VARCHAR(50)   NOT NULL,
    CONSTRAINT uk_idempotency_key_user UNIQUE (idempotency_key, username)
);
