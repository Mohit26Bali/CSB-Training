-- V4 (H2): famous lines for the sign-in screens and the quiz. The copy used by the automated tests; the MySQL original is in
-- db/migration/mysql. Table <-> entity: quotes <-> entity/Quote.

CREATE TABLE quotes (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category     VARCHAR(12)  NOT NULL,
    media_type   VARCHAR(5)   NOT NULL,
    tmdb_id      BIGINT       NOT NULL,
    title        VARCHAR(200) NOT NULL,
    release_year INT          NOT NULL,
    speaker      VARCHAR(100) NOT NULL,
    line         VARCHAR(500) NOT NULL
);
CREATE INDEX idx_quotes_category ON quotes (category);
