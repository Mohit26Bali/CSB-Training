-- V1 (H2): the same schema as db/migration/mysql/V1__accounts_and_watchlist.sql, for the in-memory database used by the
-- automated tests and the browser tests. Only the column syntax differs (BOOLEAN instead of BIT(1), TIMESTAMP(6) instead of
-- DATETIME(6), identity columns). Flyway picks the folder matching the connected database
-- (spring.flyway.locations=classpath:db/migration/{vendor}). Because the tests run Hibernate with ddl-auto=validate against this
-- schema, a test run fails if an entity and a migration ever drift apart. Keep both folders in step.

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(50)  NOT NULL,
    email        VARCHAR(100) NOT NULL,
    password     VARCHAR(100) NOT NULL,
    display_name VARCHAR(60)  NOT NULL,
    region       VARCHAR(2)   NOT NULL,
    enabled      BOOLEAN      NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE watchlist_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    tmdb_id      BIGINT       NOT NULL,
    media_type   VARCHAR(5)   NOT NULL,
    title        VARCHAR(255) NOT NULL,
    poster_path  VARCHAR(255),
    release_year INT,
    status       ENUM ('WANT', 'WATCHING', 'WATCHED') NOT NULL,
    rating       INT,
    note         VARCHAR(500),
    added_at     TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_watchlist_user_title UNIQUE (user_id, tmdb_id, media_type),
    CONSTRAINT fk_watchlist_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_watchlist_user_status ON watchlist_items (user_id, status, added_at);
