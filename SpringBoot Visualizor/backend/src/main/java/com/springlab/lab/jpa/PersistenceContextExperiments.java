package com.springlab.lab.jpa;

import com.springlab.lab.jpa.entity.Employee;
import org.springframework.stereotype.Component;
import org.springframework.transaction.TransactionStatus;

import java.util.List;
import java.util.Map;

import static com.springlab.lab.jpa.ExperimentRecorder.ev;
import static com.springlab.lab.jpa.ExperimentRecorder.nodes;

/** Entity states, the first-level cache, dirty checking, flush and commit. */
@Component
public class PersistenceContextExperiments implements ExperimentSet {

    @Override
    public Map<String, Experiment> experiments() {
        return Map.of(
                "entity-states", this::entityStates,
                "dirty-checking", this::dirtyChecking,
                "first-level-cache", this::firstLevelCache);
    }

    private void entityStates(ExperimentContext c) throws Exception {
        ExperimentRecorder rec = c.rec;
        var s = new Object() { Employee employee; Employee copy; };
        TransactionStatus tx = c.begin();
        rec.live("new", "new Employee(...)", nodes("application"), null, null,
                "A new object that no EntityManager knows. It has no id and is not in any persistence context.", null, () -> {
                    s.employee = new Employee(c.runKey, "Sam");
                    return List.of(ev("em.contains(employee)", c.em.contains(s.employee)), ev("id", s.employee.getId()));
                });
        rec.live("persist", "persist(employee)", nodes("application", "entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "persistenceContext",
                "The entity becomes MANAGED: the persistence context now tracks it. Because the key is generated by MySQL (IDENTITY), Hibernate cannot "
                        + "know the id without running the INSERT, so here the statement is executed immediately. With a sequence-based generator the INSERT "
                        + "could wait until flush; persist() does not promise SQL either way.",
                null, () -> {
                    c.em.persist(s.employee);
                    return List.of(ev("em.contains(employee)", c.em.contains(s.employee)), ev("id", s.employee.getId()));
                });
        rec.live("detach", "detach(employee)", nodes("entityManager", "persistenceContext"), "entityManager", "persistenceContext",
                "The persistence context forgets the object. It keeps its id and its data, but changes to it are no longer tracked.", null, () -> {
                    c.em.detach(s.employee);
                    return List.of(ev("em.contains(employee)", c.em.contains(s.employee)), ev("id", s.employee.getId()));
                });
        rec.live("merge", "merge(employee)", nodes("entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "jdbc",
                "merge() does not re-attach the same object. It loads the current row (a SELECT, unless the entity is already in the context) and "
                        + "returns a MANAGED copy that carries the detached object state.",
                null, () -> {
                    s.copy = c.em.merge(s.employee);
                    return List.of(ev("returned object is the same instance", s.copy == s.employee),
                            ev("em.contains(returned copy)", c.em.contains(s.copy)), ev("em.contains(original)", c.em.contains(s.employee)));
                });
        rec.live("remove", "remove(copy)", nodes("entityManager", "persistenceContext"), "entityManager", "persistenceContext",
                "The entity is scheduled for deletion; the DELETE is sent at the next flush, not now.", null, () -> {
                    c.em.remove(s.copy);
                    return List.of(ev("em.contains(copy) after remove()", c.em.contains(s.copy)));
                });
        rec.live("flush", "flush()", nodes("entityManager", "jdbc", "database"), "entityManager", "jdbc",
                "The scheduled DELETE is sent to MySQL now.", null, () -> {
                    c.em.flush();
                    return List.of();
                });
        rec.live("commit", "commit", nodes("jdbc", "database"), "jdbc", "database", "Makes the transaction permanent.", null, () -> {
            c.commit(tx);
            return List.of();
        });
        rec.infer("states", "The four states, derived from the facts above", nodes("persistenceContext"),
                "TRANSIENT: contains = false and no id. MANAGED: contains = true. DETACHED: contains = false but an id exists. REMOVED: scheduled for "
                        + "deletion (contains = false; Hibernate keeps the entry until flush). The state names are inferred from these observations.",
                List.of(ev("After new", "contains=false, id=null"), ev("After persist", "contains=true, id assigned"),
                        ev("After detach", "contains=false, id assigned"), ev("After merge", "copy: contains=true"),
                        ev("After remove", "contains=false, DELETE sent at flush")));
    }

    private void dirtyChecking(ExperimentContext c) throws Exception {
        ExperimentRecorder rec = c.rec;
        long id = c.seedEmployee("Ada", null);
        var s = new Object() { Employee employee; };
        TransactionStatus tx = c.begin();
        rec.live("find", "find(Employee.class, id)", nodes("application", "entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "jdbc",
                "The row is read and the entity becomes managed. Hibernate keeps a snapshot of its loaded state to compare against later.", null, () -> {
                    s.employee = c.em.find(Employee.class, id);
                    return List.of(ev("name", s.employee.getName()));
                });
        rec.live("change", "employee.setName(...): no save(), no persist(), no flush()", nodes("application", "persistenceContext"), "application", "entityManager",
                "Changing a field of a managed entity is plain Java. No SQL is prepared by this step.", null, () -> {
                    s.employee.setName("Ada Lovelace");
                    return List.of(ev("name in memory", s.employee.getName()));
                });
        rec.live("flush", "flush(): dirty checking finds the change", nodes("persistenceContext", "entityManager", "jdbc", "database"), "entityManager", "jdbc",
                "At flush Hibernate compares every managed entity with its snapshot. The name differs, so it prepares an UPDATE. The method that was "
                        + "never called, save(), would not have changed this: for a managed entity it adds nothing.",
                null, () -> {
                    c.em.flush();
                    return List.of();
                });
        String beforeCommit = c.inOtherTransaction(() -> c.rows("select name from jpa_lab_employee where id = ?", id));
        rec.observe("other-connection-before-commit", "What another connection sees after flush but before commit",
                nodes("database"),
                "A second database transaction reads the row. The UPDATE was sent but the transaction has not committed, so other transactions still see "
                        + "the old value. Flush sends SQL; only commit makes it visible and permanent.",
                List.of(ev("Own transaction sees", c.rows("select name from jpa_lab_employee where id = ?", id)),
                        ev("Another transaction sees", beforeCommit)));
        rec.live("commit", "commit", nodes("jdbc", "database"), "jdbc", "database", "The transaction becomes permanent and visible to others.", null, () -> {
            c.commit(tx);
            return List.of();
        });
        rec.observe("other-connection-after-commit", "What another connection sees after commit", nodes("database"),
                "Now the new value is visible everywhere.",
                List.of(ev("Another transaction sees", c.inOtherTransaction(() -> c.rows("select name from jpa_lab_employee where id = ?", id)))));
    }

    private void firstLevelCache(ExperimentContext c) throws Exception {
        ExperimentRecorder rec = c.rec;
        long id = c.seedEmployee("Ada", null);
        var s = new Object() { Employee first; };
        TransactionStatus tx = c.begin();
        rec.live("find-1", "find(Employee.class, id): first call", nodes("application", "entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "jdbc",
                "Not in the persistence context yet, so Hibernate reads the row.", null, () -> {
                    s.first = c.em.find(Employee.class, id);
                    return List.of();
                });
        rec.live("find-2", "find(Employee.class, id): second call", nodes("entityManager", "persistenceContext"), "entityManager", "persistenceContext",
                "The persistence context (the first-level cache) already holds this entity, so no statement is prepared.", null, () -> {
                    Employee again = c.em.find(Employee.class, id);
                    return List.of(ev("same instance as the first call", again == s.first));
                });
        rec.live("query", "A JPQL query returning the same row", nodes("application", "entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "jdbc",
                "A query always goes to the database, but Hibernate maps the row to the instance it already manages instead of creating a second object.", null, () -> {
                    Employee fromQuery = c.em.createQuery("select e from Employee e where e.id = :id", Employee.class).setParameter("id", id).getSingleResult();
                    return List.of(ev("same instance as the first call", fromQuery == s.first));
                });
        rec.live("clear-find", "clear(), then find() again", nodes("entityManager", "persistenceContext", "jdbc", "database"), "entityManager", "jdbc",
                "clear() empties the persistence context, so the next find() reads the row again and creates a new object.", null, () -> {
                    c.em.clear();
                    Employee fresh = c.em.find(Employee.class, id);
                    return List.of(ev("same instance as the first call", fresh == s.first));
                });
        c.commit(tx);
    }
}
